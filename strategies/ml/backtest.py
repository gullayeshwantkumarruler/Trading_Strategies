"""Portfolio construction + backtests.

Primary engine: ml4t.backtest.Engine (event-driven), orders generated by
broker.rebalance_to_weights() on the weekly signal date t (last trading day of
each week, features known at the close of t) and FILLED AT THE OPEN OF t+1
(ExecutionMode.NEXT_BAR, ExecutionPrice.OPEN).  Costs are BacktestConfig
percentage commission + percentage slippage per side.

A vectorized open-to-open replica (same weights, same timing) is used as a
cross-check of the engine and for the exact China sell-side stamp duty.
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import polars as pl

from ml4t.backtest import BacktestConfig, CommissionType, DataFeed, Engine, Strategy
from ml4t.backtest.config import (ExecutionPrice, MissingPricePolicy, ShareType,
                                  SlippageType)
from ml4t.backtest.types import ExecutionMode

QUINTILE = 0.2


def weekly_signal_dates(dates: pd.Series | np.ndarray) -> list[pd.Timestamp]:
    d = pd.DatetimeIndex(sorted(pd.unique(dates)))
    s = pd.Series(d, index=d)
    last = s.groupby(d.to_period("W-FRI")).max()
    return list(last.values.astype("datetime64[ns]"))


def cn_limit(asset: str, date: pd.Timestamp) -> float:
    code = asset.split(".")[0]
    if code.startswith("688"):
        return 0.20
    if code.startswith("300"):
        return 0.20 if date >= pd.Timestamp("2020-08-24") else 0.10
    return 0.10


def build_weights(sig: pd.DataFrame, col: str, kind: str, region: str,
                  rebal_dates: list) -> dict[pd.Timestamp, dict[str, float]]:
    """sig: date, asset, <col>, ret1.  kind: 'LS' (top-bottom quintile) or 'LO' (top quintile)."""
    sig = sig[sig["date"].isin(rebal_dates)].dropna(subset=[col])
    out = {}
    for d, g in sig.groupby("date"):
        n = len(g)
        if n < 10:
            continue
        q = max(1, int(round(n * QUINTILE)))
        g = g.sort_values(col)
        top = g.tail(q)
        w = {}
        if kind in ("LO", "LS"):
            for a in top["asset"]:
                w[a] = 1.0 / q
        if kind == "LS":
            for a in g.head(q)["asset"]:
                w[a] = -1.0 / q
        if kind == "EW":
            w = {a: 1.0 / n for a in g["asset"]}
        out[pd.Timestamp(d)] = w
    return out


class WeightsStrategy(Strategy):
    """Rebalance to precomputed weights on signal dates.

    China rules (cn=True): long-only, do not BUY a name that closed at its
    upper price limit on the signal day (order would sit in the limit-up queue),
    and do not SELL a held name that closed at its lower limit (keep weight).
    T+1 is automatically respected: positions are bought at the open of t+1
    and can only be changed at the next weekly rebalance.
    """

    def __init__(self, weights: dict, cn_flags: dict | None = None):
        self.weights = weights
        self.cn_flags = cn_flags  # {date: {asset: +1 limit-up / -1 limit-down}}
        self.blocked_buys = 0
        self.blocked_sells = 0

    def on_data(self, timestamp, data, context, broker):
        ts = pd.Timestamp(timestamp).tz_localize(None) if getattr(timestamp, "tzinfo", None) else pd.Timestamp(timestamp)
        w = self.weights.get(ts)
        if w is None:
            return
        w = dict(w)
        if self.cn_flags is not None:
            flags = self.cn_flags.get(ts, {})
            value = broker.get_account_value()
            held = {}
            for a, pos in broker.positions.items():
                if pos.quantity != 0:
                    px = data.get(a, {}).get("close") if a in data else None
                    px = px or broker._last_prices.get(a)
                    held[a] = pos.quantity * px / value if px else 0.0
            for a in list(w):
                if flags.get(a) == 1 and a not in held:
                    w.pop(a)
                    self.blocked_buys += 1
            for a, hw in held.items():
                if flags.get(a) == -1 and w.get(a, 0.0) < hw:
                    w[a] = hw
                    self.blocked_sells += 1
            tot = sum(w.values())
            if tot > 1.0:
                w = {a: v / tot for a, v in w.items()}
        broker.rebalance_to_weights(w)


def make_config(cost_bps: float, short: bool) -> BacktestConfig:
    half = cost_bps / 2 / 1e4
    return BacktestConfig(
        initial_cash=10_000_000.0,
        allow_short_selling=short,
        allow_leverage=short,
        initial_margin=0.5,
        execution_price=ExecutionPrice.OPEN,
        execution_mode=ExecutionMode.NEXT_BAR,
        share_type=ShareType.FRACTIONAL,
        commission_type=CommissionType.PERCENTAGE if cost_bps > 0 else CommissionType.NONE,
        commission_rate=half,
        slippage_type=SlippageType.PERCENTAGE if cost_bps > 0 else SlippageType.NONE,
        slippage_rate=half,
        missing_price_policy=MissingPricePolicy.USE_LAST,
        rebalance_headroom_pct=0.98,
        reject_on_insufficient_cash=True,
    )


def run_engine(px: pd.DataFrame, weights: dict, cost_bps: float, short: bool,
               start: pd.Timestamp, cn_flags: dict | None = None):
    p = px[px["date"] >= start - pd.Timedelta(days=7)]
    prices = pl.from_pandas(p[["date", "asset", "open", "high", "low", "close", "volume"]]).rename(
        {"date": "timestamp"}).with_columns(pl.col("timestamp").cast(pl.Datetime("us")))
    strat = WeightsStrategy(weights, cn_flags)
    res = Engine(DataFeed(prices_df=prices), strat, make_config(cost_bps, short)).run()
    eq = res.to_equity_dataframe().to_pandas()
    eq["timestamp"] = pd.to_datetime(eq["timestamp"]).dt.tz_localize(None).dt.normalize()
    eq = eq.set_index("timestamp")
    r = eq["equity"].pct_change().fillna(0.0)
    r = r[r.index >= start]
    return r, res, strat


def vectorized(px: pd.DataFrame, weights: dict, cost_buy: float, cost_sell: float,
               start: pd.Timestamp) -> tuple[pd.Series, pd.Series]:
    """Open-to-open daily replica: weights set at signal date t apply from open t+1.

    Returns (daily net return series indexed by date of the open where the
    period starts, turnover per rebalance).  Weights drift is ignored between
    rebalances (approximation: daily-rebalanced to target within the week).
    """
    op = px.pivot(index="date", columns="asset", values="open").sort_index()
    oo = op.shift(-1) / op - 1  # return from open d to open d+1, attributed to d
    dates = op.index
    W = pd.DataFrame(0.0, index=dates, columns=op.columns)
    tov = {}
    prev = pd.Series(0.0, index=op.columns)
    keys = sorted(weights)
    pos = dates.searchsorted(keys, side="right")  # first date strictly after signal date
    for k, i in zip(keys, pos):
        if i >= len(dates):
            continue
        w = pd.Series(weights[k]).reindex(op.columns).fillna(0.0)
        W.iloc[i:] = w.values
        dw = w - prev
        buys = dw.clip(lower=0).sum()
        sells = (-dw).clip(lower=0).sum()
        # short legs: covering is a buy, shorting is a sell; costs symmetric enough
        cs = cost_sell(dates[i]) if callable(cost_sell) else cost_sell
        tov[dates[i]] = (buys * cost_buy + sells * cs, (buys + sells) / 2)
        prev = w
    gross = (W * oo.fillna(0.0)).sum(axis=1)
    cost = pd.Series({d: c for d, (c, _) in tov.items()}).reindex(dates).fillna(0.0)
    net = (gross - cost)
    net = net[(net.index >= start)].iloc[:-1]
    turnover = pd.Series({d: t for d, (_, t) in tov.items()})
    return net, turnover


def perf(r: pd.Series, periods: int = 252) -> dict:
    r = r.dropna()
    if len(r) < 20 or r.std() == 0:
        return dict(ann_ret=np.nan, ann_vol=np.nan, sharpe=np.nan, max_dd=np.nan, n_days=len(r))
    eq = (1 + r).cumprod()
    yrs = len(r) / periods
    return dict(ann_ret=eq.iloc[-1] ** (1 / yrs) - 1, ann_vol=r.std() * np.sqrt(periods),
                sharpe=r.mean() / r.std() * np.sqrt(periods),
                max_dd=(eq / eq.cummax() - 1).min(), total_ret=eq.iloc[-1] - 1, n_days=len(r))
